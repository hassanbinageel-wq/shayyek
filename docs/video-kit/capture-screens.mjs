import { createRequire } from "module";
const require = createRequire("/opt/node22/lib/node_modules/");
const { chromium } = require("playwright");
const out = process.argv[2], theme = process.argv[3] || "light";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2.77, colorScheme: theme, isMobile: true, hasTouch: true });
await ctx.addInitScript(([t]) => { sessionStorage.setItem("shayyek.splash", "1"); localStorage.setItem("hsn_theme", t); localStorage.setItem("hsn_tips", "on"); }, [theme]);
const p = await ctx.newPage();
await p.goto("http://127.0.0.1:8787/#/"); await p.waitForSelector("input"); await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/1-login.png` });
const inputs = await p.$$("input"); await inputs[0].fill("admin"); await inputs[1].fill("a-very-strong-password");
await p.keyboard.press("Enter"); await p.waitForTimeout(3000);
await p.screenshot({ path: `${out}/2-home.png` });
await p.getByText("المزيد", { exact: true }).last().click().catch(() => {}); await p.waitForTimeout(900);
await p.screenshot({ path: `${out}/3-more.png` });
const link = p.getByText("الربط", { exact: true }).last();
const box = await link.boundingBox().catch(() => null);
console.log("linkbox", JSON.stringify(box));
await p.goto("http://127.0.0.1:8787/#/connection"); await p.waitForTimeout(2500);
await p.screenshot({ path: `${out}/4-connection.png` });
const btn = p.getByRole("button", { name: /ربط عبر Instagram/ }).first();
await btn.scrollIntoViewIfNeeded().catch(() => {}); await p.waitForTimeout(500);
console.log("btnbox", JSON.stringify(await btn.boundingBox().catch(() => null)));
await p.screenshot({ path: `${out}/5-button.png` });
await b.close();
